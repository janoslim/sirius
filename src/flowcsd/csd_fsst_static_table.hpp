/*
 * The static, dataset-agnostic FSST symbol table of the Key Idea 2 compact-tile transcoder (LEN_FSST tiles): the 95
 * printable ASCII bytes as 1-byte symbols, then general English n-grams and 2-digit numbers (no TPC-H training).
 *
 * One table, two users:
 *   - csd_fpga_runtime.cpp writes it into the transcoder's symbol memory before each compact scan (symbol-table job
 *     beats), so the FPGA compresses with exactly these symbols;
 *   - csd_fpga_assemble.cu decodes FSST bytes on the GPU with the same symbols (code -> bytes).
 *
 * Source: generated from `FsstHardwareTable::init_agnostic_default()` of
 *   gpu-smartssd-olap/fpga-offloading/five-stage-page-core/model/compact_tile_transcoder.cpp (the model the RTL is
 *   verified against). `board/csd_board_check` compares this table with the model's entry by entry at start-up and
 *   stops on any difference, so the two cannot drift apart unnoticed.
 * A symbol's code is its index. Code 255 is the escape: the next byte is a literal.
 */
